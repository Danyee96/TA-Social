<?php
/**
 * One-time web installer.
 * 1. Upload the files  2. Open https://your-domain/install.php  3. Fill in the form.
 * After a successful install this page locks itself (storage/installed.lock).
 */
declare(strict_types=1);
require __DIR__ . '/inc/bootstrap.php';
require __DIR__ . '/inc/schema.php';
require __DIR__ . '/inc/layout.php';

$lock = APP_ROOT . '/storage/installed.lock';
if (is_file($lock)) {
    auth_page('Installed', '<h1>Already installed</h1><p class="muted">The installer is locked. To reinstall, delete <code>storage/installed.lock</code> and empty the database first.</p><p><a class="btnlink primary" href="login.php">Go to sign in →</a></p>');
    exit;
}

$hasConfig = $CONFIG !== null;
$errors = [];
$v = fn($k, $d = '') => h($_POST[$k] ?? $d);

if (($_SERVER['REQUEST_METHOD'] ?? '') === 'POST') {
    $driver = $hasConfig ? cfg('db.driver', 'mysql') : (($_POST['driver'] ?? 'mysql') === 'sqlite' ? 'sqlite' : 'mysql');
    $dbc = $hasConfig ? cfg('db') : [
        'driver' => $driver,
        'host' => trim($_POST['host'] ?? 'localhost'),
        'port' => (int)($_POST['port'] ?? 3306),
        'name' => trim($_POST['dbname'] ?? ''),
        'user' => trim($_POST['dbuser'] ?? ''),
        'pass' => (string)($_POST['dbpass'] ?? ''),
        'sqlite_path' => APP_ROOT . '/storage/app.sqlite',
    ];
    $name = trim($_POST['name'] ?? '');
    $email = strtolower(trim($_POST['email'] ?? ''));
    $pass = (string)($_POST['password'] ?? '');
    $workspace = trim($_POST['workspace'] ?? 'TA Toolkit') ?: 'TA Toolkit';
    $tz = trim($_POST['timezone'] ?? 'America/New_York');

    if ($name === '') $errors[] = 'Enter your name.';
    if (!filter_var($email, FILTER_VALIDATE_EMAIL)) $errors[] = 'Enter a valid email address.';
    if (strlen($pass) < 8) $errors[] = 'Password must be at least 8 characters.';
    if (!in_array($tz, timezone_identifiers_list(), true)) $errors[] = 'Choose a valid timezone.';
    if ($driver === 'mysql' && !$hasConfig && ($dbc['name'] === '' || $dbc['user'] === '')) $errors[] = 'Enter the MySQL database name and user.';

    if (!$errors) {
        try {
            $pdo = db_connect($dbc);
        } catch (Throwable $e) {
            $errors[] = 'Could not connect to the database: ' . $e->getMessage();
        }
    }

    if (!$errors) {
        // Write config.php if it doesn't exist yet
        if (!$hasConfig) {
            $config = [
                'db' => $dbc,
                'app' => ['name' => $workspace . ' · Social Command', 'timezone' => $tz, 'force_https' => is_https(), 'debug' => false],
            ];
            $php = "<?php\n// Generated by install.php on " . date('Y-m-d H:i') . "\nreturn " . var_export($config, true) . ";\n";
            $php = str_replace("'" . APP_ROOT . "/storage/app.sqlite'", "__DIR__ . '/storage/app.sqlite'", $php);
            if (@file_put_contents(APP_ROOT . '/config.php', $php) === false) {
                $errors[] = 'Could not write config.php. Copy config.sample.php to config.php, fill it in, and reload this page.';
            } else {
                @chmod(APP_ROOT . '/config.php', 0640);
                $CONFIG = $config;
            }
        }
    }

    if (!$errors) {
        try {
            date_default_timezone_set($tz);
            $existing = false;
            try { db()->query('SELECT 1 FROM settings LIMIT 1'); $existing = true; } catch (Throwable $e) {}
            if ($existing) throw new RuntimeException('Tables already exist in this database. Use an empty database.');
            foreach (schema_sql(db_driver()) as $sql) db()->exec($sql);
            db_tx(function () use ($name, $email, $pass, $workspace) {
                seed_defaults();
                set_setting('workspace_name', $workspace);
                $rid = (int)db_val("SELECT id FROM roles WHERE slug = 'superadmin'");
                db_insert('users', [
                    'name' => $name, 'email' => $email, 'password_hash' => password_hash($pass, PASSWORD_DEFAULT),
                    'role_id' => $rid, 'title' => 'Owner', 'color' => '#00d8c6', 'active' => 1, 'session_version' => 1,
                    'created_at' => now(), 'updated_at' => now(),
                ]);
            });
            @file_put_contents($lock, date('c'));
            auth_page('Installed', '<h1>You\'re all set.</h1><p class="muted">The database is ready and your Super Admin account has been created. Sign in to add the team.</p><p><a class="btnlink primary" href="login.php">Sign in →</a></p><div class="notice">For security, the installer is now locked.</div>', $workspace);
            exit;
        } catch (Throwable $e) {
            $errors[] = 'Install failed: ' . $e->getMessage();
        }
    }
}

$err = $errors ? '<div class="formerror">' . implode('<br>', array_map('h', $errors)) . '</div>' : '';
$tzOptions = '';
$selTz = $_POST['timezone'] ?? 'America/New_York';
foreach (timezone_identifiers_list() as $z) $tzOptions .= '<option' . ($z === $selTz ? ' selected' : '') . '>' . h($z) . '</option>';

$dbFields = $hasConfig ? '<div class="notice">Using the database settings in <code>config.php</code> (' . h(cfg('db.driver')) . ').</div>' : '
<h2 class="authsec">1 · Database</h2>
<label>Database type</label>
<select name="driver" id="driver" onchange="document.getElementById(\'mysqlfields\').style.display=this.value===\'mysql\'?\'block\':\'none\'">
  <option value="mysql"' . (($_POST['driver'] ?? '') !== 'sqlite' ? ' selected' : '') . '>MySQL / MariaDB (Hostinger)</option>
  <option value="sqlite"' . (($_POST['driver'] ?? '') === 'sqlite' ? ' selected' : '') . '>SQLite (single file, no setup)</option>
</select>
<div id="mysqlfields" style="display:' . (($_POST['driver'] ?? '') === 'sqlite' ? 'none' : 'block') . '">
  <div class="formgrid"><div><label>Host</label><input name="host" value="' . $v('host', 'localhost') . '"></div><div><label>Port</label><input name="port" value="' . $v('port', '3306') . '"></div></div>
  <label>Database name</label><input name="dbname" value="' . $v('dbname') . '" placeholder="u123456789_social">
  <label>Database user</label><input name="dbuser" value="' . $v('dbuser') . '" placeholder="u123456789_social">
  <label>Database password</label><input name="dbpass" type="password" value="">
</div>';

auth_page('Install', '<h1>Set up Social Command</h1><p class="muted">Takes one minute. You\'ll be the Super Admin.</p>' . $err . '
<form method="post" autocomplete="off">' . $dbFields . '
<h2 class="authsec">' . ($hasConfig ? '1' : '2') . ' · Workspace</h2>
<div class="formgrid"><div><label>Workspace name</label><input name="workspace" value="' . $v('workspace', 'TA Toolkit') . '"></div>
<div><label>Timezone</label><select name="timezone">' . $tzOptions . '</select></div></div>
<h2 class="authsec">' . ($hasConfig ? '2' : '3') . ' · Super Admin account</h2>
<label>Your name</label><input name="name" required value="' . $v('name') . '">
<label>Email</label><input name="email" type="email" required value="' . $v('email') . '">
<label>Password (min. 8 characters)</label><input name="password" type="password" required minlength="8">
<div class="actions"><button class="primary">Install →</button></div></form>');
